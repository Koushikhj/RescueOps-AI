
import { useEffect, useState } from "react";

const API_URL = "http://localhost:5000/api/response";

function ResponseDetails() {
  const [jobId, setJobId] = useState("");
  const [job, setJob] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const fetchResults = async (id) => {
    if (!id.trim()) {
      setError("Please enter a Job ID.");
      return;
    }

    setLoading(true);
    setError("");

    try {
      const response = await fetch(
        `${API_URL}/status/${id.trim()}`
      );

      const data = await response.json();

      if (!response.ok || !data.success) {
        throw new Error(data.message || "Unable to fetch results.");
      }

      setJob(data);
    } catch (err) {
      setError(err.message);
      setJob(null);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    const params = new URLSearchParams(window.location.search);
    const id = params.get("jobId");

    if (id) {
      setJobId(id);
      fetchResults(id);
    }
  }, []);

  const result = job?.result;

  const Card = ({ title, children }) => (
    <section style={styles.card}>
      <h2>{title}</h2>
      {children}
    </section>
  );

  return (
    <main style={styles.container}>
      <h1>AI Response Details</h1>
      <p>Emergency coordination results generated by RescueOps AI.</p>

      <div style={styles.search}>
        <input
          value={jobId}
          onChange={(e) => setJobId(e.target.value)}
          placeholder="Enter your coordination Job ID"
          style={styles.input}
        />
        <button
          onClick={() => fetchResults(jobId)}
          disabled={loading}
          style={styles.button}
        >
          {loading ? "Loading..." : "Get AI Results"}
        </button>
      </div>

      {error && <p style={styles.error}>{error}</p>}

      {job && (
        <>
          <Card title="Coordination Status">
            <h3>{job.status?.toUpperCase()}</h3>
            <p>Job ID: {job.jobId}</p>
            {Object.entries(job.agentStatuses || {}).map(
              ([agent, status]) => (
                <p key={agent}>
                  {agent}: <strong>{status}</strong>
                </p>
              )
            )}
          </Card>

          {!result && (
            <p>AI agents are processing your incident. Refresh shortly.</p>
          )}

          {result && (
            <>
              <Card title="Incident Analysis">
                <p><strong>Incident:</strong> {result.analysis?.incidentType}</p>
                <p>{result.analysis?.summary}</p>
                <p><strong>Urgency:</strong> {result.analysis?.urgencyLevel}</p>
                <p><strong>People affected:</strong> {result.analysis?.affectedPeople}</p>
                <h3>Hazards</h3>
                <ul>
                  {result.analysis?.hazards?.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
                <h3>Immediate Actions</h3>
                <ul>
                  {result.analysis?.recommendedImmediateActions?.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Card>

              <Card title="Risk Assessment">
                <h2>{result.riskAssessment?.riskLevel} Risk</h2>
                <h1>{result.riskAssessment?.riskScore}/100</h1>
                <p><strong>Priority:</strong> {result.riskAssessment?.priority}</p>
                <ul>
                  {result.riskAssessment?.majorRisks?.map((item, i) => (
                    <li key={i}>{item}</li>
                  ))}
                </ul>
              </Card>

              <Card title="Resource Recommendations">
                <p>Availability: {result.resourceRecommendations?.availabilityStatus}</p>
                {result.resourceRecommendations?.requiredResources?.map(
                  (resource, i) => (
                    <div key={i} style={styles.resource}>
                      <h3>{resource.resourceType}</h3>
                      <p>Quantity: {resource.quantity}</p>
                      <p>Priority: {resource.priority}</p>
                      <p>{resource.reason}</p>
                    </div>
                  )
                )}
                <p><strong>Important:</strong> Resources are AI recommendations. Actual availability is not verified.</p>
              </Card>

              <Card title="AI Response Plan">
                <h3>{result.responsePlan?.planTitle}</h3>
                {result.responsePlan?.steps?.map((step) => (
                  <div key={step.step} style={styles.resource}>
                    <h3>Step {step.step}: {step.action}</h3>
                    <p>Responsible team: {step.responsibleTeam}</p>
                    <p>Priority: {step.priority}</p>
                  </div>
                ))}
                <p><strong>Human approval required:</strong> Yes</p>
                <p><strong>Dispatch status:</strong> {result.responsePlan?.dispatchStatus}</p>
              </Card>

              <Card title="Performance">
                <p>Total execution time: {result.performance?.totalPipelineTimeSeconds} seconds</p>
              </Card>
            </>
          )}
        </>
      )}
    </main>
  );
}

const styles = {
  container: {
    padding: "30px",
    color: "#e5e7eb",
    background: "#111827",
    minHeight: "100vh",
  },
  search: {
    display: "flex",
    gap: "12px",
    flexWrap: "wrap",
    margin: "24px 0",
  },
  input: {
    flex: "1",
    minWidth: "240px",
    padding: "12px",
    borderRadius: "8px",
    border: "1px solid #475569",
    background: "#1f2937",
    color: "white",
  },
  button: {
    padding: "12px 20px",
    border: "none",
    borderRadius: "8px",
    background: "#2563eb",
    color: "white",
    cursor: "pointer",
  },
  card: {
    background: "#1f2937",
    padding: "22px",
    borderRadius: "12px",
    marginBottom: "20px",
    border: "1px solid #374151",
  },
  resource: {
    padding: "12px",
    margin: "12px 0",
    borderRadius: "8px",
    background: "#374151",
  },
  error: {
    color: "#f87171",
  },
};

export default ResponseDetails;
